-- ESUP-2223: check-in events for NDelius. Rows are written in the same transaction as the change
-- they describe and published by CheckinDeliusEventRelayJob, one check-in at a time and in id
-- order, so NDelius receives each check-in's events in the order they happened.
--
-- Lifecycle events (scheduled, rescheduled, cancelled, link delivered / not delivered) carry their
-- detail in the row: NDelius fetches /v2/events/{type}/{event_id} and gets the notes and date as
-- they were when the event happened. With the feature on, the existing check-in events (received,
-- expired, reviewed, updated) go through here too, to keep their order; their detail is built
-- from the check-in as before, and detail_id is the id their detail endpoint expects.
CREATE TABLE checkin_delius_event_v2 (
    "id" bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "event_id" uuid NOT NULL CONSTRAINT uk_checkin_delius_event_v2_event_id UNIQUE,
    "event_type" varchar(64) NOT NULL,
    -- the id in the detail URL: event_id, the check-in UUID, or the annotation's log entry UUID
    "detail_id" uuid NOT NULL,
    "checkin_uuid" uuid NOT NULL,
    "crn" varchar(7) NOT NULL,
    "event_number" bigint,
    -- the check-in date the event refers to (scheduled and rescheduled only)
    "date_time" timestamp with time zone,
    -- NULL when the detail is built from the check-in
    "notes" text,
    "occurred_at" timestamp with time zone NOT NULL,
    "published_at" timestamp with time zone,
    "publish_attempts" integer NOT NULL DEFAULT 0,
    "last_error" text
);

-- Only rescheduling and annotating can happen more than once for a check-in.
CREATE UNIQUE INDEX uk_checkin_delius_event_v2_once_per_checkin
    ON checkin_delius_event_v2 (checkin_uuid, event_type)
    WHERE event_type NOT IN ('V2_CHECKIN_RESCHEDULED', 'V2_CHECKIN_ANNOTATED');

CREATE INDEX idx_checkin_delius_event_v2_checkin ON checkin_delius_event_v2 (checkin_uuid, id);

CREATE INDEX idx_checkin_delius_event_v2_unpublished ON checkin_delius_event_v2 (id)
    WHERE published_at IS NULL;

--rollback DROP TABLE IF EXISTS checkin_delius_event_v2;
